def _format_bot_log_tail(log_file: Path, n_lines: int = 80) -> str:
    """Last `n_lines` of the bot's log file, for failure-message context."""
    if not log_file.exists():
        return "(no log file)"
    lines = log_file.read_text().splitlines()
    return "\n".join(lines[-n_lines:])


@pytest.fixture
def bot_log_tail(
    bot_process: tuple[subprocess.Popen[bytes], Path],
) -> Any:
    """Callable that returns the tail of the bot's stdout, for assertions
    and for failure-message context."""
    _, log_file = bot_process

    def _tail(n_lines: int = 80) -> str:
        return _format_bot_log_tail(log_file, n_lines)

    return _tail


# Make conv-style helper available without per-test imports.
async def send_and_get_reply(client: Any, bot: str, text: str, timeout: float = 20.0) -> Any:
    """Send `text` to `bot` and return the bot's first reply Message.

    Uses Telethon's `Conversation` so we don't get tripped up by stale
    messages from previous test runs.
    """
    async with client.conversation(bot, timeout=timeout) as conv:
        await conv.send_message(text)
        return await conv.get_response()


